import Foundation
import HealthKit

/// A measurement HealthKit can divide into workout zones. Requires read access to the matching type
/// (`.heartRate` or `.cyclingPower`) to see zone data.
public enum WorkoutZoneMetric: Sendable, CaseIterable {
    case heartRate
    case cyclingPower

    /// The unit of every zone boundary: `BPM` or `W`.
    public var unit: String {
        switch self {
        case .heartRate: "BPM"
        case .cyclingPower: "W"
        }
    }

    var quantityType: HKQuantityType {
        switch self {
        case .heartRate: HKQuantityType(.heartRate)
        case .cyclingPower: HKQuantityType(.cyclingPower)
        }
    }

    var healthKitUnit: HKUnit {
        switch self {
        case .heartRate: HKUnit.count().unitDivided(by: .minute())
        case .cyclingPower: .watt()
        }
    }

    init?(quantityType: HKQuantityType) {
        guard let metric = Self.allCases.first(where: { $0.quantityType == quantityType }) else { return nil }
        self = metric
    }
}

/// The ranges that divide a metric into zones, such as five heart rate zones.
public struct WorkoutZoneConfiguration: Sendable, Equatable {

    /// Where the zones came from.
    public enum Source: Sendable {
        /// Generated by the system from the person's health metrics.
        case system
        /// Set manually by the person in Health settings.
        case user
        /// Defined by an app for a single workout.
        case app
    }

    public struct Zone: Sendable, Equatable {
        /// Zero-based, ordered from the lowest to the highest range.
        public let index: Int
        /// `nil` for the lowest zone.
        public let minimum: Double?
        /// `nil` for the highest zone.
        public let maximum: Double?

        public init(index: Int, minimum: Double?, maximum: Double?) {
            self.index = index
            self.minimum = minimum
            self.maximum = maximum
        }

        init(_ zone: HKWorkoutZone, unit: HKUnit) {
            self.init(index: zone.index, minimum: zone.minimum?.doubleValue(for: unit), maximum: zone.maximum?.doubleValue(for: unit))
        }
    }

    public let metric: WorkoutZoneMetric
    public let source: Source
    public let zones: [Zone]

    public init(metric: WorkoutZoneMetric, source: Source = .app, zones: [Zone]) {
        self.metric = metric
        self.source = source
        self.zones = zones
    }

    /// Creates app-defined zones from ascending boundaries, for example `[120, 140, 160, 175]` BPM.
    ///
    /// `n` boundaries produce `n + 1` zones. Throws `HealthHubError.invalidQuery` when HealthKit rejects
    /// the boundaries, such as when they are not strictly ascending and greater than zero.
    public init(metric: WorkoutZoneMetric, boundaries: [Double]) throws {
        let healthKitConfiguration: HKWorkoutZoneConfiguration
        do {
            healthKitConfiguration = try HKWorkoutZoneConfiguration(
                quantityType: metric.quantityType,
                zoneBoundaries: boundaries.map { HKQuantity(unit: metric.healthKitUnit, doubleValue: $0) }
            )
        } catch {
            throw HealthHubError.invalidQuery(error.localizedDescription)
        }
        self.init(metric: metric, healthKitConfiguration)
    }

    init(metric: WorkoutZoneMetric, _ configuration: HKWorkoutZoneConfiguration) {
        let unit = metric.healthKitUnit
        self.init(
            metric: metric,
            source: Source(configuration.source),
            zones: configuration.zones.map { Zone($0, unit: unit) }
        )
    }

    func healthKitConfiguration() throws -> HKWorkoutZoneConfiguration {
        try HKWorkoutZoneConfiguration(
            quantityType: metric.quantityType,
            zoneBoundaries: zones.compactMap(\.minimum).map { HKQuantity(unit: metric.healthKitUnit, doubleValue: $0) }
        )
    }
}

private extension WorkoutZoneConfiguration.Source {

    init(_ source: HKWorkoutZoneConfiguration.Source) {
        switch source {
        case .system: self = .system
        case .user: self = .user
        case .app: self = .app
        @unknown default: self = .app
        }
    }
}

/// The zones a workout used for one metric and the time spent in each.
public struct WorkoutZoneGroup: Sendable, Equatable {

    public struct TimeInZone: Sendable, Equatable {
        public let zone: WorkoutZoneConfiguration.Zone
        public let duration: TimeInterval

        public init(zone: WorkoutZoneConfiguration.Zone, duration: TimeInterval) {
            self.zone = zone
            self.duration = duration
        }
    }

    public let configuration: WorkoutZoneConfiguration
    /// Ordered from the lowest to the highest zone.
    public let timeInZones: [TimeInZone]

    public init(configuration: WorkoutZoneConfiguration, timeInZones: [TimeInZone]) {
        self.configuration = configuration
        self.timeInZones = timeInZones
    }

    public var metric: WorkoutZoneMetric { configuration.metric }

    /// Total time spent across all zones, in seconds.
    public var totalDuration: TimeInterval {
        timeInZones.reduce(0) { $0 + $1.duration }
    }

    init(metric: WorkoutZoneMetric, _ group: HKWorkoutZoneGroup) {
        let unit = metric.healthKitUnit
        configuration = WorkoutZoneConfiguration(metric: metric, group.configuration)
        timeInZones = group.zoneDurations.map {
            TimeInZone(zone: .init($0.zone, unit: unit), duration: $0.duration)
        }
    }

    /// Converts HealthKit's per-type zone groups, ordered by `WorkoutZoneMetric.allCases` and skipping unsupported types.
    static func groups(from groupsByType: [HKQuantityType: HKWorkoutZoneGroup]?) -> [WorkoutZoneGroup] {
        guard let groupsByType else { return [] }
        return WorkoutZoneMetric.allCases.compactMap { metric in
            groupsByType[metric.quantityType].map { WorkoutZoneGroup(metric: metric, $0) }
        }
    }
}
